//go:build !ike_complexity_only

package main

import (
	"fmt"
	"go/format"
	"os"
	"slices"
	"strings"
	"testing"

	"ike/internal/lang"
)

// complexityOnlyLangsFile is the generated detection table of the
// complexity-only build (#2939).
const complexityOnlyLangsFile = "complexityonly_langs.go"

// TestComplexityOnlyLangTable keeps complexityonly_langs.go in step with the
// full build's language registry. The complexity-only binary links only the
// spec'd language plugins; every other language reaches it through this
// table, so a file the full build reports as "skipped: … (no complexity spec:
// yaml)" is skipped the same way there. The table is derived from the full
// registry — exactly the extensions and file names that resolve to each
// language here — so a language added, renamed or re-patterned fails this
// test until the table is regenerated:
//
//	IKE_GEN_COMPLEXITY_LANGS=1 go test ./cmd/ike -run TestComplexityOnlyLangTable
func TestComplexityOnlyLangTable(t *testing.T) {
	want, err := renderComplexityOnlyLangs()
	if err != nil {
		t.Fatal(err)
	}
	if os.Getenv("IKE_GEN_COMPLEXITY_LANGS") != "" {
		if err := os.WriteFile(complexityOnlyLangsFile, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(complexityOnlyLangsFile)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != string(want) {
		t.Fatalf("%s is stale; regenerate with\n\tIKE_GEN_COMPLEXITY_LANGS=1 go test ./cmd/ike -run TestComplexityOnlyLangTable", complexityOnlyLangsFile)
	}
}

// renderComplexityOnlyLangs renders the table from the live registry: the
// ids of every spec'd language (which the complexity-only build must link as
// plugins) and a detection-only entry for every other language, carrying the
// extensions and file names that resolve to it in this build.
func renderComplexityOnlyLangs() ([]byte, error) {
	var spec []string
	var b strings.Builder
	b.WriteString("// Code generated by TestComplexityOnlyLangTable (cmd/ike/complexityonly_langs_test.go); DO NOT EDIT.\n")
	b.WriteString("// Regenerate: IKE_GEN_COMPLEXITY_LANGS=1 go test ./cmd/ike -run TestComplexityOnlyLangTable\n\n")
	b.WriteString("//go:build ike_complexity_only\n\npackage main\n\nimport \"ike/internal/lang\"\n\n")
	b.WriteString("// detectionOnlyLanguages are the languages without a complexity spec, by\n")
	b.WriteString("// id and the file patterns that resolve to them in the full build.\n")
	b.WriteString("var detectionOnlyLanguages = []lang.Language{\n")
	for _, l := range lang.All() {
		if l.Complexity != nil {
			spec = append(spec, l.ID)
			continue
		}
		var exts, names []string
		for _, e := range l.Extensions {
			if r, ok := lang.ByExt(e); ok && r.ID == l.ID && !slices.Contains(exts, e) {
				exts = append(exts, e)
			}
		}
		for _, n := range l.Filenames {
			if r, ok := lang.ByPath(n); ok && r.ID == l.ID && !slices.Contains(names, n) {
				names = append(names, n)
			}
		}
		fmt.Fprintf(&b, "\t{ID: %q", l.ID)
		if len(exts) > 0 {
			fmt.Fprintf(&b, ", Extensions: %s", goStrings(exts))
		}
		if len(names) > 0 {
			fmt.Fprintf(&b, ", Filenames: %s", goStrings(names))
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n\n")
	b.WriteString("// complexitySpecLanguages are the languages with a complexity spec in the\n")
	b.WriteString("// full build; the complexity-only build must register each with its spec.\n")
	fmt.Fprintf(&b, "var complexitySpecLanguages = %s\n", goStrings(spec))
	return format.Source([]byte(b.String()))
}

func goStrings(xs []string) string {
	q := make([]string, len(xs))
	for i, x := range xs {
		q[i] = fmt.Sprintf("%q", x)
	}
	return "[]string{" + strings.Join(q, ", ") + "}"
}
