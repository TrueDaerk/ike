// The Windows package-manager manifests (#3002). Both describe the full-build
// Windows zip of one release: the Scoop manifest installs it as an app with a
// WezTerm dependency and a Start-menu entry, the winget set as a portable
// package with a wez.wezterm dependency. The release workflow regenerates
// them from the built archives and commits them back to main.

const (
	repo        = "TrueDaerk/ike"
	wingetID    = "TrueDaerk.Ike"
	wingetSchem = "1.9.0"
)

// arches maps the Go architecture of a Windows archive to its name in the
// Scoop and winget manifests.
var arches = []struct{ goarch, scoop, winget string }{
	{"amd64", "64bit", "x64"},
	{"arm64", "arm64", "arm64"},
}

// release is everything the manifests carry that changes per release.
type release struct {
	Version string
	Date    string            // YYYY-MM-DD, winget ReleaseDate
	Hashes  map[string]string // goarch → SHA-256 of the Windows full-build zip
}

func archiveName(ver, goarch string) string {
	return fmt.Sprintf("ike_%s_windows_%s.zip", ver, goarch)
}

func archiveURL(ver, goarch string) string {
	return fmt.Sprintf("https://github.com/%s/releases/download/v%s/%s", repo, ver, archiveName(ver, goarch))
}

var sha256Hex = regexp.MustCompile(`^[0-9a-f]{64}$`)

// releaseFromChecksums picks the Windows full-build zips out of the release's
// checksums.txt.
func releaseFromChecksums(ver, date string, sums map[string]string) (release, error) {
	rel := release{Version: ver, Date: date, Hashes: map[string]string{}}
	for _, a := range arches {
		name := archiveName(ver, a.goarch)
		h, ok := sums[name]
		if !ok {
			return rel, fmt.Errorf("%s is missing from %s", name, checksumsFile)
		}
		if !sha256Hex.MatchString(h) {
			return rel, fmt.Errorf("%s: %q is not a SHA-256", name, h)
		}
		rel.Hashes[a.goarch] = h
	}
	return rel, nil
}

// scoopManifest renders deploy/scoop/ike.json. The Start-menu entry runs
// wezterm-gui.exe from the Scoop wezterm dependency directly (a .cmd target
// would flash a console window) with the dedicated config, which runs the
// ike.exe next to it; ike-gui.cmd stays on PATH for terminal launches.
func scoopManifest(rel release) ([]byte, error) {
	arch := map[string]any{}
	for _, a := range arches {
		arch[a.scoop] = map[string]string{
			"url":  archiveURL(rel.Version, a.goarch),
			"hash": rel.Hashes[a.goarch],
		}
	}
	autoArch := map[string]any{}
	for _, a := range arches {
		autoArch[a.scoop] = map[string]string{
			"url": fmt.Sprintf("https://github.com/%s/releases/download/v$version/ike_$version_windows_%s.zip", repo, a.goarch),
		}
	}
	m := orderedMap{
		{"version", rel.Version},
		{"description", "IKE, a JetBrains-inspired terminal IDE with vim-style editing, launched in a dedicated WezTerm window"},
		{"homepage", "https://github.com/" + repo},
		{"license", orderedMap{
			{"identifier", "MIT with Commons Clause"},
			{"url", "https://github.com/" + repo + "/blob/main/LICENSE"},
		}},
		{"depends", "extras/wezterm"},
		{"notes", []string{
			"Start IKE from the Start menu (Ike) or run `ike-gui` in a project directory.",
			"`ike` alone runs IKE in the current terminal.",
		}},
		{"architecture", arch},
		{"bin", []string{"ike.exe", "ike-gui.cmd", "keyprobe.exe"}},
		{"shortcuts", [][]string{{
			`..\..\wezterm\current\wezterm-gui.exe`,
			"Ike",
			`--config-file "$dir\wezterm-ike.lua" start --always-new-process`,
			"ike.ico",
		}}},
		{"checkver", orderedMap{{"github", "https://github.com/" + repo}}},
		{"autoupdate", orderedMap{
			{"architecture", autoArch},
			{"hash", orderedMap{{"url", fmt.Sprintf("https://github.com/%s/releases/download/v$version/checksums.txt", repo)}}},
		}},
	}
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "    ")
	if err := enc.Encode(m); err != nil {
		return nil, err
	}
	return buf.Bytes(), nil
}

// wingetManifests renders the three files of deploy/winget/<version>/, keyed
// by file name.
func wingetManifests(rel release) map[string]string {
	head := func(kind string) string {
		return fmt.Sprintf("# Generated by `go run ./cmd/release manifests` (#3002) — do not edit.\n"+
			"# yaml-language-server: $schema=https://aka.ms/winget-manifest.%s.%s.schema.json\n\n"+
			"PackageIdentifier: %s\nPackageVersion: %s\n", kind, wingetSchem, wingetID, rel.Version)
	}
	tail := func(kind string) string {
		return fmt.Sprintf("ManifestType: %s\nManifestVersion: %s\n", kind, wingetSchem)
	}

	var inst strings.Builder
	inst.WriteString(head("installer"))
	inst.WriteString("InstallerType: zip\n" +
		"NestedInstallerType: portable\n" +
		"NestedInstallerFiles:\n" +
		"  - RelativeFilePath: ike.exe\n" +
		"    PortableCommandAlias: ike\n" +
		// ConPTY, which IKE's integrated terminal and WezTerm build on,
		// arrived in Windows 10 1809.
		"MinimumOSVersion: 10.0.17763.0\n" +
		"Dependencies:\n" +
		"  PackageDependencies:\n" +
		"    - PackageIdentifier: wez.wezterm\n")
	fmt.Fprintf(&inst, "ReleaseDate: %s\nInstallers:\n", rel.Date)
	for _, a := range arches {
		fmt.Fprintf(&inst, "  - Architecture: %s\n    InstallerUrl: %s\n    InstallerSha256: %s\n",
			a.winget, archiveURL(rel.Version, a.goarch), strings.ToUpper(rel.Hashes[a.goarch]))
	}
	inst.WriteString(tail("installer"))

	var loc strings.Builder
	loc.WriteString(head("defaultLocale"))
	fmt.Fprintf(&loc, "PackageLocale: en-US\n"+
		"Publisher: TrueDaerk\n"+
		"PublisherUrl: https://github.com/TrueDaerk\n"+
		"PackageName: IKE\n"+
		"PackageUrl: https://github.com/%[1]s\n"+
		"License: MIT with Commons Clause\n"+
		"LicenseUrl: https://github.com/%[1]s/blob/main/LICENSE\n"+
		"ShortDescription: A JetBrains-inspired terminal IDE with vim-style editing.\n"+
		"Description: |-\n"+
		"  IKE is a terminal IDE with windowing, tabs and panes, vim-style editing,\n"+
		"  LSP code intelligence and Tree-sitter highlighting. It needs a terminal\n"+
		"  that speaks the Kitty keyboard protocol; this package depends on WezTerm.\n"+
		"  Run install-desktop.ps1 from the package directory for a Start-menu entry.\n"+
		"Moniker: ike\n"+
		"Tags:\n  - editor\n  - ide\n  - terminal\n  - tui\n  - vim\n"+
		"ReleaseNotesUrl: https://github.com/%[1]s/releases/tag/v%[2]s\n", repo, rel.Version)
	loc.WriteString(tail("defaultLocale"))

	ver := head("version") + "DefaultLocale: en-US\n" + tail("version")

	return map[string]string{
		wingetID + ".yaml":              ver,
		wingetID + ".installer.yaml":    inst.String(),
		wingetID + ".locale.en-US.yaml": loc.String(),
	}
}

// writeManifests rewrites deploy/scoop/ike.json and deploy/winget/<version>/
// below root; older deploy/winget/<version> directories are removed, so the
// tree always carries exactly the latest release's set.
func writeManifests(root string, rel release) error {
	scoop, err := scoopManifest(rel)
	if err != nil {
		return err
	}
	scoopPath := filepath.Join(root, "deploy", "scoop", "ike.json")
	if err := os.MkdirAll(filepath.Dir(scoopPath), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(scoopPath, scoop, 0o644); err != nil {
		return err
	}
	wingetRoot := filepath.Join(root, "deploy", "winget")
	old, _ := os.ReadDir(wingetRoot)
	for _, e := range old {
		if e.IsDir() && e.Name() != rel.Version {
			if err := os.RemoveAll(filepath.Join(wingetRoot, e.Name())); err != nil {
				return err
			}
		}
	}
	dir := filepath.Join(wingetRoot, rel.Version)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for name, body := range wingetManifests(rel) {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o644); err != nil {
			return err
		}
	}
	return nil
}

// orderedMap is a JSON object that keeps its key order, so the manifest
// reads top-down like the hand-written ones in the Scoop buckets.
type orderedMap []struct {
	k string
	v any
}

func (m orderedMap) MarshalJSON() ([]byte, error) {
	var buf bytes.Buffer
	buf.WriteByte('{')
	for i, kv := range m {
		if i > 0 {
			buf.WriteByte(',')
		}
		k, err := json.Marshal(kv.k)
		if err != nil {
			return nil, err
		}
		v, err := marshalNoEscape(kv.v)
		if err != nil {
			return nil, err
		}
		buf.Write(k)
		buf.WriteByte(':')
		buf.Write(v)
	}
	buf.WriteByte('}')
	return buf.Bytes(), nil
}

func marshalNoEscape(v any) ([]byte, error) {
	var buf bytes.Buffer
	enc := json.NewEncoder(&buf)
	enc.SetEscapeHTML(false)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	return bytes.TrimRight(buf.Bytes(), "\n"), nil
}
